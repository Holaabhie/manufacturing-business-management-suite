// Also compile TypeScript modules in apps/web/src/messages/*.ts
function updateTs(locale, jsonPath, tsPath) {
  const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const content = `// Generated messages for ${locale}\nconst messages = ${JSON.stringify(data, null, 2)} as const;\nexport default messages;\n`;
  fs.writeFileSync(tsPath, content, 'utf8');
  console.log('Updated', tsPath);
}

